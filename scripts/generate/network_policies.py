#!/usr/bin/env python3
"""Generate the network policies: default-deny everywhere, then only the calls made (ADR 0047).

    uv run python -m scripts.generate.network_policies

K8S-001 and EGR-001. Each namespace denies all ingress and egress, with a Kubernetes NetworkPolicy,
then Cilium policies allow each workload exactly the calls it makes, and outside the cluster only
the named endpoints it needs, by DNS name.

The calls are read, not written by hand, so a new call is covered once this runs again, and a test
fails until it does:
- **Settings:** each `WINDOPS_..._ADDRESS` or `_URL` a workload's code reads, or a shared library it
  uses reads, resolved through `.env.example`, which `make config` copies into windops-settings.
- **Addresses in its own manifests or code:** an in-cluster name in its env, its ConfigMaps or its
  source, such as the Weather Service's recordings at the Evaluation Service.
- **Data stores, by the Secrets it reads:** `-database` is PostgreSQL, `-events` NATS and `-cache`
  Redis.
- **Declared below,** with the reason: what is in neither, such as the gateway's routes, which live
  in etcd, and the Agent Runtime's MCP servers, whose addresses it builds.

Ports are the pods' own, not the Services', because Cilium decides after a Service picks a pod.
"""

import re
import subprocess
import sys
import tomllib
from collections import defaultdict
from collections.abc import Iterable, Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

REPOSITORY = Path(__file__).resolve().parents[2]
KUBERNETES = REPOSITORY / "infrastructure" / "kubernetes"
OUTPUT = KUBERNETES / "base" / "network"
HEADER = "# Generated by scripts/generate/network_policies.py. Do not edit: run it again instead.\n"

NAMESPACES = (
    "windops-system",
    "windops-application",
    "windops-mcp",
    "windops-data",
    "windops-observability",
)
# Each list of resources, and the Kustomize directories that hold the workloads.
SERVICE_LISTS = (KUBERNETES / "base" / "services", KUBERNETES / "base" / "development")
PLATFORM = (
    KUBERNETES / "base" / "data",
    KUBERNETES / "base" / "observability",
    REPOSITORY / "infrastructure" / "gateway" / "etcd",
    REPOSITORY / "infrastructure" / "security" / "keycloak",
)
# The gateway's routes and plugin settings live in etcd, put there from these.
GATEWAY_CONFIG = (
    REPOSITORY / "infrastructure" / "gateway" / "routes",
    REPOSITORY / "infrastructure" / "gateway" / "plugin-metadata",
)
SETTINGS = REPOSITORY / ".env.example"
NAME = "app.kubernetes.io/name"
COMPONENT = "app.kubernetes.io/component"
NAMESPACE_LABEL = "k8s:io.kubernetes.pod.namespace"
MIGRATION = "migration"
# The namespaces whose services have databases, so run migration Jobs.
MIGRATING = ("windops-system", "windops-application")
POSTGRES = "windops-postgres"

# An in-cluster address: name.namespace.svc, with or without the cluster's domain and a port.
IN_CLUSTER = re.compile(
    r"(?P<scheme>https?://)?(?P<service>windops-[a-z0-9-]+)\.(?P<namespace>windops-[a-z]+)"
    r"\.svc(?:\.cluster\.local)?(?::(?P<port>\d+))?"
)
VARIABLE = re.compile(r"\$\(([A-Z0-9_]+)\)")
SETTING = re.compile(r"\bWINDOPS_[A-Z0-9_]+_(?:ADDRESS|URL|ENDPOINT)\b")

# The Secret suffixes that name a data store, and the store.
STORE_SECRETS = {
    "-database": ("windops-postgres", "windops-data", 5432),
    "-events": ("windops-nats", "windops-data", 4222),
    "-cache": ("windops-redis", "windops-data", 6379),
    "-keycloak": ("windops-keycloak", "windops-system", 8443),
}


@dataclass(frozen=True, order=True)
class Peer:
    name: str
    namespace: str
    port: int


@dataclass(frozen=True)
class External:
    """A named endpoint outside the cluster (SRS 9.3, EGR-001)."""

    purpose: str
    names: tuple[str, ...]
    patterns: tuple[str, ...] = ()
    port: int = 443


ANTHROPIC = External("Anthropic API", ("api.anthropic.com",))
LANGSMITH = External("LangSmith traces", ("api.smith.langchain.com",))
# A sandbox's data plane is the address LangSmith's API gives for it, so only a pattern can name it.
LANGSMITH_SANDBOX = External(
    "LangSmith Sandbox", ("api.smith.langchain.com",), patterns=("*.langchain.com",)
)
TAVILY = External("Tavily web research", ("api.tavily.com",))
EMBEDDINGS = External("Embedding provider", ("api.openai.com",))
FORECASTS = External("Forecast provider", ("api.open-meteo.com",))

# Outside the cluster: each workload's named endpoints, and nothing else (EGR-001).
EXTERNAL: dict[str, tuple[External, ...]] = {
    "windops-agent-runtime": (ANTHROPIC, LANGSMITH),
    "windops-agent-sandbox-adapter": (LANGSMITH_SANDBOX,),
    "windops-external-intelligence": (TAVILY,),
    "windops-knowledge": (EMBEDDINGS,),
    "windops-weather": (FORECASTS,),
}

# Calls that neither settings nor manifests show, each with its reason.
DECLARED: dict[str, tuple[tuple[Peer, str], ...]] = {
    "windops-agent-runtime": tuple(
        (Peer(f"windops-mcp-{server}", "windops-mcp", 8443), "its tools, at addresses it builds")
        for server in ("documentation", "tavily", "weather", "windops")
    ),
    "windops-fluent-bit": (
        (
            Peer("windops-loki", "windops-observability", 3100),
            "sends logs, its host and port apart",
        ),
    ),
}

# Scraped at a port its pod does not announce, as its own job (prometheus.yml).
UNANNOUNCED_METRICS = {"windops-kube-state-metrics": 8080}
# Entities Cilium names: the Kubernetes API, for those that watch it.
API_SERVER = {
    "windops-prometheus": "finds pods and nodes, and reads container figures through it",
    "windops-kube-state-metrics": "reports the cluster's objects",
    "windops-fluent-bit": "labels each log line with its pod",
}
# Who may reach the gateway: anyone, as the platform's only way in (SRS 9.5).
EDGE = "windops-gateway"
PROMETHEUS = Peer("windops-prometheus", "windops-observability", 0)
CERT_MANAGER_METRICS = 9402
# Cilium's operator runs on the node's own network, so it is the host to Cilium, not a pod.
HOST_METRICS = {9963: "Cilium's operator"}


@dataclass
class Workload:
    name: str
    namespace: str
    ports: dict[str, int]
    metrics_port: int | None
    secrets: set[str]
    texts: list[str] = field(default_factory=list)
    source: Path | None = None
    services: dict[tuple[str, int], int] = field(default_factory=dict)


def render(directory: Path) -> list[dict[str, Any]]:
    out = subprocess.run(
        ["kubectl", "kustomize", str(directory)], capture_output=True, text=True, check=True
    ).stdout
    return [document for document in yaml.safe_load_all(out) if document]


def resources(listing: Path) -> list[Path]:
    kustomization = yaml.safe_load((listing / "kustomization.yaml").read_text())
    return [(listing / entry).resolve() for entry in kustomization["resources"]]


def pod_spec(document: dict[str, Any]) -> dict[str, Any]:
    spec: dict[str, Any] = document["spec"]["template"]["spec"]
    return spec


def config_maps(spec: dict[str, Any]) -> set[str]:
    """The ConfigMaps a pod reads, other than windops-settings, which every service reads."""
    names: set[str] = set()
    for container in spec.get("containers", []) + spec.get("initContainers", []):
        names |= {
            s["configMapRef"]["name"] for s in container.get("envFrom", []) if "configMapRef" in s
        }
        for item in container.get("env", []):
            if ref := (item.get("valueFrom") or {}).get("configMapKeyRef"):
                names.add(ref["name"])
    names |= {v["configMap"]["name"] for v in spec.get("volumes", []) if "configMap" in v}
    return names - {"windops-settings"}


def workloads_of(documents: list[dict[str, Any]], source: Path | None) -> list[Workload]:
    maps = {
        (d["metadata"].get("namespace"), d["metadata"]["name"]): yaml.safe_dump(d.get("data", {}))
        for d in documents
        if d["kind"] == "ConfigMap"
    }
    found = []
    for document in documents:
        if document["kind"] not in ("Deployment", "StatefulSet", "DaemonSet"):
            continue
        spec, template = pod_spec(document), document["spec"]["template"]["metadata"]
        namespace = document["metadata"]["namespace"]
        containers = spec["containers"]
        annotation = (template.get("annotations") or {}).get("prometheus.io/port")
        found.append(
            Workload(
                name=template["labels"][NAME],
                namespace=namespace,
                ports={
                    p.get("name", str(p["containerPort"])): p["containerPort"]
                    for c in containers
                    for p in c.get("ports", [])
                },
                metrics_port=int(annotation) if annotation else None,
                secrets={
                    ref["name"]
                    for c in containers
                    for item in c.get("env", [])
                    if (ref := (item.get("valueFrom") or {}).get("secretKeyRef"))
                },
                texts=[yaml.safe_dump(containers)]
                + [maps[(namespace, m)] for m in config_maps(spec) if (namespace, m) in maps],
                source=source,
            )
        )
    return found


def all_workloads() -> list[Workload]:
    found: list[Workload] = []
    services: list[dict[str, Any]] = []
    for listing in SERVICE_LISTS:
        for deploy in resources(listing):
            documents = render(deploy)
            services += [d for d in documents if d["kind"] == "Service"]
            found += workloads_of(documents, deploy.parent)
    for directory in PLATFORM:
        documents = render(directory)
        services += [d for d in documents if d["kind"] == "Service"]
        found += workloads_of(documents, None)
    by_selector = {(w.namespace, w.name): w for w in found}
    for service in services:
        meta = service["metadata"]
        target = by_selector.get((meta["namespace"], service["spec"]["selector"].get(NAME)))
        if target is None:
            continue
        for port in service["spec"]["ports"]:
            pod_port = port.get("targetPort", port["port"])
            if isinstance(pod_port, str):
                pod_port = target.ports[pod_port]
            target.services[(meta["name"], port["port"])] = pod_port
    return sorted(found, key=lambda w: (w.namespace, w.name))


def settings() -> dict[str, str]:
    values = {}
    for line in SETTINGS.read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            key, _, value = line.partition("=")
            values[key.strip()] = value.strip()
    return values


def shared_libraries(source: Path) -> list[Path]:
    """The workspace's shared libraries a workload uses, and those they use in turn."""
    shared = {
        tomllib.loads((p / "pyproject.toml").read_text())["project"]["name"]: p
        for p in (REPOSITORY / "shared").iterdir()
        if (p / "pyproject.toml").exists()
    }
    seen: list[Path] = []
    pending = [source]
    while pending:
        project = tomllib.loads((pending.pop() / "pyproject.toml").read_text())["project"]
        for requirement in project.get("dependencies", []):
            name = re.split(r"[<>=!~ \[;]", requirement, maxsplit=1)[0]
            if (library := shared.get(name)) and library not in seen:
                seen.append(library)
                pending.append(library)
    return seen


def code_texts(source: Path) -> Iterator[tuple[str, bool]]:
    """Each Python file a workload runs, and whether it is the workload's own."""
    for directory, own in [(source, True), *((s, False) for s in shared_libraries(source))]:
        for path in sorted((directory / "src").rglob("*.py")):
            yield path.read_text(), own


class Resolver:
    """Turns an in-cluster address into the workload behind it, on its pod's port."""

    def __init__(self, workloads: list[Workload]) -> None:
        self.services = {
            (w.namespace, service, port): Peer(w.name, w.namespace, pod_port)
            for w in workloads
            for (service, port), pod_port in w.services.items()
        }

    def peer(self, match: re.Match[str]) -> Peer | None:
        default = 443 if match["scheme"] == "https://" else 80
        port = int(match["port"]) if match["port"] else default
        return self.services.get((match["namespace"], match["service"], port))

    def peers_in(self, text: str) -> set[Peer]:
        return {peer for match in IN_CLUSTER.finditer(text) if (peer := self.peer(match))}


def calls(workloads: list[Workload]) -> dict[str, dict[Peer, str]]:
    """Each workload's calls inside the cluster, and why each is allowed."""
    resolver, values = Resolver(workloads), settings()
    found: dict[str, dict[Peer, str]] = defaultdict(dict)
    for workload in workloads:
        made = found[workload.name]
        for text in workload.texts:
            # Kubernetes fills in each $(NAME) in an env value from windops-settings.
            text = VARIABLE.sub(lambda m: values.get(m[1], m[0]), text)
            for peer in resolver.peers_in(text):
                made.setdefault(peer, "named in its manifests")
        for secret in sorted(workload.secrets):
            for suffix, (store, namespace, port) in STORE_SECRETS.items():
                if secret.endswith(suffix):
                    made.setdefault(Peer(store, namespace, port), f"reads Secret {secret}")
        if workload.source is not None and (workload.source / "pyproject.toml").exists():
            for text, own in code_texts(workload.source):
                for setting in sorted(set(SETTING.findall(text))):
                    for peer in resolver.peers_in(values.get(setting, "")):
                        made.setdefault(peer, f"reads {setting}")
                if own:
                    for peer in resolver.peers_in(text):
                        made.setdefault(peer, "named in its code")
        for peer, reason in DECLARED.get(workload.name, ()):
            made.setdefault(peer, reason)
    gateway = found[EDGE]
    for directory in GATEWAY_CONFIG:
        for route in sorted(directory.glob("*.json")):
            for peer in resolver.peers_in(route.read_text()):
                gateway.setdefault(peer, f"its {directory.name} {route.stem}")
    # A pod reaching itself, such as through its own Service, needs no rule.
    return {name: {p: r for p, r in made.items() if p.name != name} for name, made in found.items()}


# ---- The policies ----------------------------------------------------------------------------


def endpoint(name: str, namespace: str) -> dict[str, Any]:
    return {"matchLabels": {NAME: name, NAMESPACE_LABEL: namespace}}


def ports(numbers: Iterable[int]) -> list[dict[str, Any]]:
    return [{"ports": [{"port": str(n), "protocol": "TCP"} for n in sorted(set(numbers))]}]


def metadata(name: str, namespace: str) -> dict[str, Any]:
    return {
        "name": name,
        "namespace": namespace,
        "labels": {"app.kubernetes.io/part-of": "windops"},
    }


def default_deny(namespace: str) -> dict[str, Any]:
    return {
        "apiVersion": "networking.k8s.io/v1",
        "kind": "NetworkPolicy",
        "metadata": metadata("windops-default-deny", namespace),
        "spec": {"podSelector": {}, "policyTypes": ["Ingress", "Egress"]},
    }


def cilium(name: str, namespace: str, description: str, spec: dict[str, Any]) -> dict[str, Any]:
    return {
        "apiVersion": "cilium.io/v2",
        "kind": "CiliumNetworkPolicy",
        "metadata": metadata(name, namespace),
        "spec": {"description": description, **spec},
    }


def dns(namespace: str) -> dict[str, Any]:
    """Every pod may ask the cluster's DNS, through Cilium's proxy, which learns each name's
    addresses, so a rule by DNS name can allow them."""
    return cilium(
        "windops-dns",
        namespace,
        "Every pod may look names up, through Cilium's DNS proxy",
        {
            "endpointSelector": {},
            "egress": [
                {
                    "toEndpoints": [
                        {"matchLabels": {NAMESPACE_LABEL: "kube-system", "k8s:k8s-app": "kube-dns"}}
                    ],
                    "toPorts": [
                        {
                            "ports": [
                                {"port": "53", "protocol": "UDP"},
                                {"port": "53", "protocol": "TCP"},
                            ],
                            "rules": {"dns": [{"matchPattern": "*"}]},
                        }
                    ],
                }
            ],
        },
    )


def scraping(namespace: str, metrics: set[int]) -> dict[str, Any]:
    return cilium(
        "windops-metrics",
        namespace,
        "Prometheus may read each pod's metrics",
        {
            "endpointSelector": {},
            "ingress": [
                {
                    "fromEndpoints": [endpoint(PROMETHEUS.name, PROMETHEUS.namespace)],
                    "toPorts": ports(metrics),
                }
            ],
        },
    )


def migrations(namespace: str) -> dict[str, Any]:
    return cilium(
        "windops-migrations",
        namespace,
        "Migration Jobs reach only PostgreSQL",
        {
            "endpointSelector": {"matchLabels": {COMPONENT: MIGRATION}},
            "egress": [
                {
                    "toEndpoints": [endpoint("windops-postgres", "windops-data")],
                    "toPorts": ports([5432]),
                }
            ],
        },
    )


def group(peers: Iterable[Peer]) -> list[dict[str, Any]]:
    """One rule per port, listing who is on the other side."""
    by_port: dict[int, set[tuple[str, str]]] = defaultdict(set)
    for peer in peers:
        by_port[peer.port].add((peer.name, peer.namespace))
    return [
        {"endpoints": [endpoint(n, ns) for n, ns in sorted(by_port[port])], "port": port}
        for port in sorted(by_port)
    ]


def workload_policy(
    workload: Workload, callers: set[Peer], made: dict[Peer, str], scraped: set[int]
) -> dict[str, Any]:
    ingress: list[dict[str, Any]] = [
        {"fromEndpoints": rule["endpoints"], "toPorts": ports([rule["port"]])}
        for rule in group(callers)
    ]
    if workload.name == POSTGRES:
        ingress.append(
            {
                "fromEndpoints": [
                    {"matchLabels": {COMPONENT: MIGRATION, NAMESPACE_LABEL: namespace}}
                    for namespace in MIGRATING
                ],
                "toPorts": ports([workload.ports["postgres"]]),
            }
        )
    if workload.name == EDGE:
        ingress.insert(
            0, {"fromEntities": ["world", "cluster"], "toPorts": ports([workload.ports["https"]])}
        )
    egress: list[dict[str, Any]] = [
        {"toEndpoints": rule["endpoints"], "toPorts": ports([rule["port"]])} for rule in group(made)
    ]
    if workload.name == PROMETHEUS.name:
        egress.append(
            {
                "toEndpoints": [
                    {"matchExpressions": [{"key": NAMESPACE_LABEL, "operator": "Exists"}]}
                ],
                "toPorts": ports(scraped),
            }
        )
    if workload.name == PROMETHEUS.name:
        egress.append({"toEntities": ["host", "remote-node"], "toPorts": ports(HOST_METRICS)})
    if workload.name in API_SERVER:
        egress.append({"toEntities": ["kube-apiserver"], "toPorts": ports([443, 6443, 8443])})
    for external in EXTERNAL.get(workload.name, ()):
        egress.append(
            {
                "toFQDNs": [{"matchName": n} for n in external.names]
                + [{"matchPattern": p} for p in external.patterns],
                "toPorts": ports([external.port]),
            }
        )
    # A direction with nothing allowed is left out: the namespace's default-deny covers it.
    spec: dict[str, Any] = {"endpointSelector": {"matchLabels": {NAME: workload.name}}}
    if ingress:
        spec["ingress"] = ingress
    if egress:
        spec["egress"] = egress
    return cilium(workload.name, workload.namespace, describe(workload), spec)


def describe(workload: Workload) -> str:
    external = [e.purpose for e in EXTERNAL.get(workload.name, ())]
    text = f"{workload.name}: only the calls it makes and receives"
    return text + (", and outside the cluster only " + ", ".join(external) if external else "")


def generate() -> dict[str, str]:
    workloads = all_workloads()
    made = calls(workloads)
    keyed = {w.name: w for w in workloads}
    for name in EXTERNAL:
        if name not in keyed:
            raise ValueError(f"{name} has named endpoints but is not a workload")
    callers: dict[str, set[Peer]] = defaultdict(set)
    for source, peers in made.items():
        for peer in peers:
            callers[peer.name].add(Peer(source, keyed[source].namespace, peer.port))
    metrics: dict[str, set[int]] = defaultdict(set)
    for workload in workloads:
        port = workload.metrics_port or UNANNOUNCED_METRICS.get(workload.name)
        if port:
            metrics[workload.namespace].add(port)
    # Ours, and cert-manager's, in its own namespace.
    scraped = {p for numbers in metrics.values() for p in numbers} | {CERT_MANAGER_METRICS}
    files: dict[str, str] = {}
    for namespace in NAMESPACES:
        documents = [default_deny(namespace), dns(namespace)]
        if metrics[namespace]:
            documents.append(scraping(namespace, metrics[namespace]))
        if namespace in MIGRATING:
            documents.append(migrations(namespace))
        for workload in (w for w in workloads if w.namespace == namespace):
            documents.append(
                workload_policy(workload, callers[workload.name], made[workload.name], scraped)
            )
        files[f"{namespace}.yaml"] = HEADER + yaml.safe_dump_all(documents, sort_keys=False)
    files["kustomization.yaml"] = HEADER + yaml.safe_dump(
        {
            "apiVersion": "kustomize.config.k8s.io/v1beta1",
            "kind": "Kustomization",
            "resources": [f"{n}.yaml" for n in NAMESPACES],
        },
        sort_keys=False,
    )
    return files


def main() -> int:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for path, text in generate().items():
        (OUTPUT / path).write_text(text)
        print(f"wrote {(OUTPUT / path).relative_to(REPOSITORY)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
