def dashboards() -> dict[str, str]:
    """Our dashboards for Managed Grafana. Every panel uses Prometheus, so only its uid moves."""
    out = {}
    for path in sorted((MONITORING / "grafana" / "dashboards").glob("*.json")):
        text = path.read_text().replace('"uid": "prometheus"', f'"uid": "{DATASOURCE}"')
        out[path.name] = text
    return out


def _json(body: dict[str, Any]) -> str:
    return (
        json.dumps({"generatedBy": "scripts/generate/azure_monitoring.py", **body}, indent=2) + "\n"
    )


def generate() -> dict[Path, str]:
    groups, moved = rule_groups()
    files: dict[Path, str] = {
        CLUSTER_OUT / "collector.yaml": HEADER + yaml.safe_dump_all(collector(), sort_keys=False),
        CLUSTER_OUT / "ama-metrics-prometheus-config.yaml": HEADER
        + yaml.safe_dump(scrape_config(), sort_keys=False),
        CLUSTER_OUT / "kustomization.yaml": HEADER
        + yaml.safe_dump(
            {
                "apiVersion": "kustomize.config.k8s.io/v1beta1",
                "kind": "Kustomization",
                "resources": ["collector.yaml", "ama-metrics-prometheus-config.yaml"],
            },
            sort_keys=False,
        ),
        AZURE_OUT / "prometheus-rule-groups.json": _json(
            {"groups": groups, "coveredByServiceBusAlerts": moved}
        ),
        AZURE_OUT / "servicebus-alerts.json": _json({"alerts": SERVICE_BUS_ALERTS}),
    }
    for name, text in dashboards().items():
        files[AZURE_OUT / "grafana" / name] = text
    return files


def main() -> int:
    files = generate()
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"Wrote {len(files)} Azure Monitor files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
