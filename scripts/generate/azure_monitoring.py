#!/usr/bin/env python3
"""Generate Azure Monitor's configuration from the local observability stack (ADR 0006).

    uv run python -m scripts.generate.azure_monitoring

On Azure, the same signals go to Azure's own services, so nothing in a service changes:

| Signal | Locally | On Azure |
| --- | --- | --- |
| Traces | OpenTelemetry Collector, to Tempo | The same Collector, to Application Insights |
| Logs | Fluent Bit, to Loki | Container insights reads stdout, into Log Analytics |
| Metrics | Prometheus scrapes annotated pods | Managed Prometheus scrapes them, with the same job |
| Alerts | Prometheus rules | Azure Prometheus rule groups, and Service Bus metric alerts |
| Dashboards | Grafana | Azure Managed Grafana, on the Azure Monitor workspace |

Everything here is made from the local files, so the two cannot drift: a test fails until this runs
again. Values only Azure knows are `${AZURE_...}` placeholders for the Azure deployment to fill.
"""

import copy
import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml

REPOSITORY = Path(__file__).resolve().parents[2]
MONITORING = REPOSITORY / "infrastructure" / "monitoring"
CLUSTER_OUT = MONITORING / "azure"
AZURE_OUT = REPOSITORY / "infrastructure" / "azure" / "monitoring"
# The contrib build has the azuremonitor exporter. The same version as the local Collector.
CONTRIB_IMAGE = (
    "otel/opentelemetry-collector-contrib:0.164.0"
    "@sha256:340c9ca6a36617084c6661bdc4f0fe92b7cda5a805d61673ec8db375fddc522b"
)
# The Secret's name, not a secret.
CONNECTION_SECRET = "windops-otel-collector-appinsights"  # noqa: S105
HEADER = "# Generated by scripts/generate/azure_monitoring.py. Do not edit: run it again instead.\n"
# Azure Monitor alert severity: 0 is critical, 4 is verbose.
SEVERITY = {"critical": 1, "warning": 2, "info": 3}
DATASOURCE = "${AZURE_PROMETHEUS_DATASOURCE_UID}"


def placeholder(name: str) -> str:
    return "${" + name + "}"


def iso_duration(value: str) -> str:
    """5m is PT5M, as Azure Monitor writes durations."""
    found = re.fullmatch(r"(\d+)([smhd])", value)
    if not found:
        raise ValueError(f"Not a Prometheus duration: {value}")
    amount, unit = found.groups()
    return f"P{amount}D" if unit == "d" else f"PT{amount}{unit.upper()}"


def collector() -> list[dict[str, Any]]:
    """The local Collector, sending traces to Application Insights instead of Tempo."""
    local = [d for d in yaml.safe_load_all((MONITORING / "otel-collector" / "collector.yaml")
                                           .read_text()) if d]  # fmt: skip
    config_map = next(d for d in local if d["kind"] == "ConfigMap")
    config = yaml.safe_load(config_map["data"]["config.yaml"])
    config["exporters"] = {
        "azuremonitor": {"connection_string": "${env:APPLICATIONINSIGHTS_CONNECTION_STRING}"}
    }
    for pipeline in config["service"]["pipelines"].values():
        pipeline["exporters"] = ["azuremonitor"]
    out: list[dict[str, Any]] = []
    for document in local:
        document = copy.deepcopy(document)
        if document["kind"] == "ConfigMap":
            document["data"]["config.yaml"] = yaml.safe_dump(config, sort_keys=False)
        if document["kind"] == "Deployment":
            spec = document["spec"]["template"]["spec"]
            spec["serviceAccountName"] = "windops-otel-collector"
            document["spec"]["template"]["metadata"].setdefault("labels", {})[
                "azure.workload.identity/use"] = "true"  # fmt: skip
            container = spec["containers"][0]
            container["image"] = CONTRIB_IMAGE
            container.setdefault("env", []).append(
                {
                    "name": "APPLICATIONINSIGHTS_CONNECTION_STRING",
                    "valueFrom": {"secretKeyRef": {"name": CONNECTION_SECRET,
                                                   "key": "connection-string"}},
                }
            )  # fmt: skip
            container.setdefault("volumeMounts", []).append(
                {"name": "secrets-store", "mountPath": "/mnt/secrets-store", "readOnly": True}
            )
            spec.setdefault("volumes", []).append(
                {
                    "name": "secrets-store",
                    "csi": {"driver": "secrets-store.csi.k8s.io", "readOnly": True,
                            "volumeAttributes": {"secretProviderClass": "windops-otel-collector"}},
                }
            )  # fmt: skip
        out.append(document)
    client_id = placeholder("AZURE_CLIENT_ID_WINDOPS_OTEL_COLLECTOR")
    out.append(
        {
            "apiVersion": "v1",
            "kind": "ServiceAccount",
            "metadata": {
                "name": "windops-otel-collector",
                "annotations": {"azure.workload.identity/client-id": client_id},
            },
        }
    )
    out.append(
        {
            "apiVersion": "secrets-store.csi.x-k8s.io/v1",
            "kind": "SecretProviderClass",
            "metadata": {"name": "windops-otel-collector"},
            "spec": {
                "provider": "azure",
                "parameters": {
                    "clientID": client_id,
                    "keyvaultName": placeholder("AZURE_KEYVAULT_NAME"),
                    "tenantId": placeholder("AZURE_TENANT_ID"),
                    "objects": yaml.safe_dump({"array": [yaml.safe_dump(
                        {"objectName": "appinsights-connection-string",
                         "objectType": "secret"})]}),
                },
                "secretObjects": [
                    {
                        "secretName": CONNECTION_SECRET,
                        "type": "Opaque",
                        "data": [{"key": "connection-string",
                                  "objectName": "appinsights-connection-string"}],
                    }
                ],
            },
        }
    )  # fmt: skip
    return out


def scrape_config() -> dict[str, Any]:
    """Managed Prometheus's extra scrape config: our own pods job, exactly as locally."""
    local = yaml.safe_load((MONITORING / "prometheus" / "prometheus.yml").read_text())
    pods = next(job for job in local["scrape_configs"] if job["job_name"] == "pods")
    return {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {"name": "ama-metrics-prometheus-config", "namespace": "kube-system"},
        # Managed Prometheus already gathers kube-state-metrics and cAdvisor itself.
        "data": {"prometheus-config": yaml.safe_dump({"scrape_configs": [pods]}, sort_keys=False)},
    }


def rule_groups() -> tuple[list[dict[str, Any]], list[str]]:
    """Azure Prometheus rule groups from ours, and the alerts left to Service Bus's own metrics."""
    local = yaml.safe_load((MONITORING / "prometheus" / "rules.yml").read_text())
    groups, moved = [], []
    for group in local["groups"]:
        rules = []
        for rule in group["rules"]:
            if "jetstream_" in rule["expr"]:
                # JetStream is local only. On Azure, Service Bus's metric alerts cover these.
                moved.append(rule["alert"])
                continue
            labels = rule.get("labels", {})
            rules.append(
                {
                    "alert": rule["alert"],
                    "expression": rule["expr"],
                    "for": iso_duration(rule["for"]) if "for" in rule else "PT0M",
                    "severity": SEVERITY[labels.get("severity", "warning")],
                    "labels": labels,
                    "annotations": rule.get("annotations", {}),
                    "enabled": True,
                }
            )
        if rules:
            groups.append({"name": group["name"], "interval": "PT1M", "rules": rules})
    return groups, moved


