#!/usr/bin/env python3
"""Generate the `azure` Kustomize overlay: Workload ID and Key Vault for every workload (ADR 0006).

    uv run python -m scripts.generate.azure_overlay

It reads the base manifests, so a new service is covered once this runs again, and a test fails
until it does. For each Deployment that reads a Secret:

- it gets its own service account, for its Microsoft Entra workload identity, and the label that
  turns Workload ID on;
- its database password and NATS login are removed: on Azure it signs in to PostgreSQL and
  Service Bus with Entra instead, with no stored secret;
- every other Secret it reads comes from Key Vault, through the Secrets Store CSI driver, which
  syncs Kubernetes Secrets of the same names, so the Deployment itself barely changes.

Values that only Azure knows, such as each workload's client ID, are `${AZURE_...}` placeholders.
The Azure deployment fills them in, as the gateway routes' settings are filled in.
"""

import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

REPOSITORY = Path(__file__).resolve().parents[2]
BASE = REPOSITORY / "infrastructure" / "kubernetes" / "base" / "services"
OVERLAY = REPOSITORY / "infrastructure" / "kubernetes" / "overlays" / "azure"
# Replaced on Azure by Entra: PostgreSQL by a token, and NATS by Service Bus (ADR 0006).
REMOVED = frozenset(
    {
        "WINDOPS_DATABASE_PASSWORD",
        "WINDOPS_EVENTS_URL",
        "WINDOPS_EVENTS_USERNAME",
        "WINDOPS_EVENTS_PASSWORD",
    }
)
MOUNT = "/mnt/secrets-store"
VOLUME = "secrets-store"
HEADER = "# Generated by scripts/generate/azure_overlay.py. Do not edit: run it again instead.\n"


def placeholder(name: str) -> str:
    return "${" + name + "}"


def client_id_setting(workload: str) -> str:
    """windops-asset's client ID is ${AZURE_CLIENT_ID_WINDOPS_ASSET}."""
    return f"AZURE_CLIENT_ID_{workload.upper().replace('-', '_')}"


def vault_secret_name(secret: str, key: str) -> str:
    """windops-internal-identity's signing-key is windops-internal-identity--signing-key."""
    return f"{secret}--{key}"


def base_documents() -> list[dict[str, Any]]:
    rendered = subprocess.run(
        ["kubectl", "kustomize", str(BASE)], capture_output=True, text=True, check=True
    ).stdout
    return [d for d in yaml.safe_load_all(rendered) if d]


def secret_references(deployment: dict[str, Any]) -> list[tuple[str, str, str, str]]:
    """(container, variable, Secret, key) for every Secret a Deployment's env reads."""
    found = []
    for container in deployment["spec"]["template"]["spec"]["containers"]:
        for item in container.get("env") or []:
            ref = (item.get("valueFrom") or {}).get("secretKeyRef")
            if ref:
                found.append((container["name"], item["name"], ref["name"], ref["key"]))
    return found


def workload_documents(deployment: dict[str, Any]) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """The service account and SecretProviderClass, and the patch, for one Deployment."""
    name = deployment["metadata"]["name"]
    namespace = deployment["metadata"]["namespace"]
    references = secret_references(deployment)
    kept = sorted({(secret, key) for _, var, secret, key in references if var not in REMOVED})
    client_id = placeholder(client_id_setting(name))
    account = {
        "apiVersion": "v1",
        "kind": "ServiceAccount",
        "metadata": {
            "name": name,
            "namespace": namespace,
            "labels": {"app.kubernetes.io/name": name, "app.kubernetes.io/part-of": "windops"},
            "annotations": {"azure.workload.identity/client-id": client_id},
        },
    }
    objects = [{"objectName": vault_secret_name(s, k), "objectType": "secret"} for s, k in kept]
    synced: dict[str, list[dict[str, str]]] = {}
    for secret, key in kept:
        synced.setdefault(secret, []).append(
            {"key": key, "objectName": vault_secret_name(secret, key)}
        )
    provider = {
        "apiVersion": "secrets-store.csi.x-k8s.io/v1",
        "kind": "SecretProviderClass",
        "metadata": {"name": name, "namespace": namespace},
        "spec": {
            "provider": "azure",
            "parameters": {
                # Signed in as this workload's own identity, through Workload ID.
                "clientID": client_id,
                "keyvaultName": placeholder("AZURE_KEYVAULT_NAME"),
                "tenantId": placeholder("AZURE_TENANT_ID"),
                "objects": yaml.safe_dump({"array": [yaml.safe_dump(o) for o in objects]}),
            },
            "secretObjects": [
                {"secretName": secret, "type": "Opaque", "data": data}
                for secret, data in sorted(synced.items())
            ],
        },
    }
    containers: dict[str, list[dict[str, Any]]] = {}
    for container, variable, _, _ in references:
        if variable in REMOVED:
            containers.setdefault(container, []).append({"name": variable, "$patch": "delete"})
    first = deployment["spec"]["template"]["spec"]["containers"][0]["name"]
    patch_containers = []
    for container in [c["name"] for c in deployment["spec"]["template"]["spec"]["containers"]]:
        entry: dict[str, Any] = {"name": container}
        if containers.get(container):
            entry["env"] = containers[container]
        if container == first:
            # Mounting it is what makes the driver sync the Kubernetes Secrets.
            entry["volumeMounts"] = [{"name": VOLUME, "mountPath": MOUNT, "readOnly": True}]
        patch_containers.append(entry)
    patch = {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": name, "namespace": namespace},
        "spec": {
            "template": {
                "metadata": {"labels": {"azure.workload.identity/use": "true"}},
                "spec": {
                    "serviceAccountName": name,
                    "containers": patch_containers,
                    "volumes": [
                        {
                            "name": VOLUME,
                            "csi": {
                                "driver": "secrets-store.csi.k8s.io",
                                "readOnly": True,
                                "volumeAttributes": {"secretProviderClass": name},
                            },
                        }
                    ],
                },
            }
        },
    }
    return [account, provider], patch


def generate() -> dict[str, str]:
    """Every file of the overlay, by its path inside it."""
    deployments = sorted(
        (d for d in base_documents() if d["kind"] == "Deployment" and secret_references(d)),
        key=lambda d: d["metadata"]["name"],
    )
    identities: list[dict[str, Any]] = []
    files: dict[str, str] = {}
    patches = []
    for deployment in deployments:
        documents, patch = workload_documents(deployment)
        identities += documents
        path = f"patches/{deployment['metadata']['name']}.yaml"
        files[path] = HEADER + yaml.safe_dump(patch, sort_keys=False)
        patches.append({"path": path})
    files["workload-identity.yaml"] = HEADER + yaml.safe_dump_all(identities, sort_keys=False)
    kustomization = {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "resources": ["../../base/namespaces", "../../base/services", "workload-identity.yaml"],
        "patches": patches,
    }
    files["kustomization.yaml"] = (
        HEADER
        + "# Azure (ADR 0006): Workload ID and Key Vault for every workload. The Azure\n"
        + "# deployment fills the ${AZURE_...} placeholders before applying it.\n"
        + yaml.safe_dump(kustomization, sort_keys=False)
    )
    return files


def main() -> int:
    files = generate()
    for old in OVERLAY.glob("patches/*.yaml"):
        if f"patches/{old.name}" not in files:
            old.unlink()
    for path, text in files.items():
        target = OVERLAY / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    print(
        f"Wrote the azure overlay: {len(files) - 2} workloads, in {OVERLAY.relative_to(REPOSITORY)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
